def response_rules() -> list[sc.DerivedList]:
    """Each DERIVED list as it reads ONE response table: its own response source or an `also` one
    (campaignQuest / campaignMap hold the client's own table at login and a response's in a session)."""
    rules = []
    for rule in sc.DERIVED:
        for source in (rule.source,) + rule.also:
            if source[0] == 'response':
                rules.append(sc.DerivedList(rule.key, rule.table, source, rule.fields, rule.gate, rule.evidence,
                                            rule.where))
    return rules


def rules() -> list[sc.DerivedList]:
    """Every list this fixture's manifest derives from what the server serves: the response tables' and the
    served area table (with its join over the client's own F_DUNGEON_MST)."""
    return response_rules() + [AREA]


def derivation(mst: Path) -> list[tuple]:
    """[(rule, rows, joined, files)] for rules() over the server's mst_root and banner folder."""
    out = []
    for rule in rules():
        rows, files, _identity = sc.derived_rows(rule, mst, BANNERS)
        joined, more, _identities = sc.joined_rows(rule, mst, BANNERS)
        out.append((rule, rows, joined, files + more))
    return out


def required_names(mst: Path) -> list[tuple[str, str]]:
    """(folder, name) of every name what the server serves from `mst` makes a startup list ask for."""
    out = set()
    for rule, rows, joined, _files in derivation(mst):
        out |= {(f.folder.strip('/'), name) for name, f in sc.derived_names(rule, rows, joined)[0]}
    return sorted(out)


def generate(fx: dict, mst: Path) -> dict:
    """The manifest startup_coverage derives for this fixture from what the server serves from `mst` -- the
    generator's own reader (derived_rows, joined_rows), rules (build_manifest) and inputs entries (root mst,
    the SHA-256 of each table read; root served, the area table's projection; the client's own dungeon
    table)."""
    derived, server_files, client_files = [], [], list(fx['client_files'])
    for rule, rows, joined, files in derivation(mst):
        derived.append((rule, rows, joined))
        for f in files:
            listed = server_files if f['root'] in sc.SERVER_ROOTS else client_files
            if all((g['root'], g['path'].lower()) != (f['root'], f['path'].lower()) for g in listed):
                listed.append(f)
    manifest, _report = sc.build_manifest(
        sc.Content(fx['content']), scene=[LOGIN], res_paths=[], packaged=set(), categories=[], derived=derived,
        build=BUILD, inputs={'client_files': client_files, 'server_files': server_files})
    return manifest


def build_fixture() -> dict:
    if WORK.exists():
        shutil.rmtree(WORK)
    mst = WORK / 'mst'
    # A COPY (new files): deploy/mst's tables are hard-linked elsewhere, so nothing here may link them.
    shutil.copytree(REAL_MST, mst, copy_function=shutil.copyfile)
    content = WORK / 'game_content' / 'content'
    cw.put(content / 'login' / LOGIN, b'\x89PNG\r\n\x1a\nfixture login')
    for folder, name in required_names(mst):
        cw.put(content / folder / name, b'fixture ' + name.encode())
    system = WORK / 'system'
    system.mkdir(parents=True)
    for real in (ROOT / 'deploy' / 'system').glob('*.json'):
        if real.name not in ('content_provider.json', 'content_startup.json'):
            shutil.copyfile(real, system / real.name)
    exts = sorted({p.suffix.lower() for p in content.rglob('*') if p.is_file()} | {'.png'})
    policy = {'enabled': True, 'scope': ['**'], 'aliases': {}, 'extensions': exts,
              'exclude': ['UserDefault.xml', 'XMLFileProcessor.xml', '*.dat', '*.xml', '*.ini', '*.tmp', '*.json',
                          '*.zip', 'Thumbs.db', '.DS_*'], 'bundles': {}}
    client = WORK / 'client'
    table = cw.put(client / 'LocalState' / 'Ver1_Fixture1.dat', b'a master table of the fixture client')
    client_files = [{'root': 'localstate', 'path': 'Ver1_Fixture1.dat', 'sha256': hashlib.sha256(table).hexdigest()}]
    return {'mst': mst, 'content': content, 'system': system, 'policy': policy, 'client_files': client_files}


def write_system(fx: dict, manifest) -> None:
    (fx['system'] / 'content_provider.json').write_text(json.dumps(fx['policy'], indent=1), encoding='utf-8')
    text = manifest if isinstance(manifest, str) else json.dumps(manifest, indent=1)
    (fx['system'] / 'content_startup.json').write_text(text, encoding='utf-8')


def server(exe: Path, label: str) -> IsolatedServer:
    sfx = Fixture.create(SERVER_DIR, port=PORT, document_root=WORK / 'game_content', system_root=WORK / 'system',
                         mst_root=WORK / 'mst', keep=True)
    return IsolatedServer(exe, sfx, log_name=f'server_{label}.log')


def server_log(label: str) -> str:
    return (SERVER_DIR / f'server_{label}.log').read_text(encoding='utf-8', errors='replace')


def status_tables(broker: Broker) -> dict[str, str]:
    """{server_input_name: sha256 hex} of the status T rows: what the server serves, as it parsed it."""
    code, _h, body = broker.get('/status')
    out = {}
    for line in body.decode().splitlines():
        parts = line.split('\t')
        if parts[0] == 'T' and len(parts) == 4 and parts[1] in sc.SERVER_ROOTS and parts[3].startswith('sha256:'):
            out[sc.server_input_name(parts[1], parts[2])] = parts[3][len('sha256:'):]
    return out


def served_rows(srv: IsolatedServer) -> dict[str, list]:
    """response key -> rows, from this server's Initialize, UserInfo and CampaignMissionGet replies."""
    client = Client(srv.fx)
    out = {}
    for group, key in (INITIALIZE, KEYS['UserInfo'], CAMPAIGN_MISSION_GET):
        reply = client.call(group, key, {})
        assert 'error' not in reply, (group, reply)
        out.update({k: v for k, v in reply.items() if isinstance(v, list)})
    return out


DUNGEONS = {0: sc.load_version_table('F_DUNGEON_MST')[1]}    # the area list's join: the client's own table


def served_names(rows: dict[str, list]) -> dict[str, list[str]]:
    """response key -> the names its rows make a startup list ask for (startup_coverage's rules)."""
    out = {rule.source[2]: sorted({n.lower() for n, _f in sc.derived_names(rule, rows.get(rule.source[2]))[0]})
           for rule in response_rules() if rows.get(rule.source[2]) is not None}
    if rows.get('3SG2wX0R') is not None:
        out['3SG2wX0R'] = sorted({n.lower() for n, _f in sc.derived_names(AREA, rows['3SG2wX0R'], DUNGEONS)[0]})
    return out


def file_names(mst: Path) -> dict[str, list[str]]:
    """The same, predicted by the generator from the server's mst_root and banner folder."""
    out = {}
    for rule, rows, joined, _files in derivation(mst):
        out[rule.source[2] if rule.source[0] == 'response' else rule.source[1]] = sorted(
            {n.lower() for n, _f in sc.derived_names(rule, rows, joined)[0]})
    return out


def projection_of(rows: dict[str, list]) -> str:
    """sha256 hex of the served projection of the area rows UserInfo actually sent."""
    return hashlib.sha256(sc.served_projection('3SG2wX0R', rows['3SG2wX0R'])).hexdigest()


def verdict(check: Checker, label: str, cov: dict, offline: dict, *, complete: bool, reason: str | None = None) -> None:
    """The report, the DLL's rule and the offline evaluation agree on `complete`; an incomplete report
    gives `reason` exactly (when given)."""
    want = '1' if complete else '0'
    ok = cov.get('complete') == want and cov['proved'] == complete and offline['complete'] == complete
    if reason is not None:
        ok = ok and cov.get('reason') == reason
    check(f'{label}: complete {want} -- the broker, the DLL\'s rule and the offline evaluation agree'
          + (' on the reason' if reason is not None else ''), ok,
          {'broker': cov.get('complete'), 'dll': cov['proved'], 'offline': offline['complete'],
           'reason': cov.get('reason'), 'want reason': reason, 'offline binding': offline.get('server_binding'),
           'why': cov['why']})


def first_plate(mst: Path) -> str:
    """A served area plate ending in .png that has no translated copy yet (the banner case's subject)."""
    return next(r['H0UB8pqm'] for r in sc.served_area_rows(mst, BANNERS) if r['H0UB8pqm'].endswith('.png'))


def main() -> int:
    exe = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / 'out/qa/current/session19/bin/gimuserverw.exe')
    check = Checker()
    real_before = sc.served_tables(REAL_MST, None)
    fx = build_fixture()
    mst, content = fx['mst'], fx['content']
    original = (mst / BANNER).read_bytes()
    area_original = (mst / 'area_mst.json').read_bytes()
    files_before = {n: d for n, d in sc.served_tables(mst, BANNERS).items() if not n.startswith('served:')}
    check('fixture: the server tables are copies of deploy/mst (same bytes, their own files -- never links), and '
          'the server\'s working folder has no banner folder yet',
          files_before == {n: d for n, d in real_before.items() if not n.startswith('served:')} and len(files_before) == 6
          and all(os.stat(mst / n).st_nlink == 1 for n in files_before) and not BANNERS.exists(), files_before)
    m0 = generate(fx, mst)
    names0 = set(m0['sets']['background'])
    check(f'fixture: the generated manifest requires every name the served tables derive ({len(names0)}), nothing '
          'absent or unknown, and names the six tables and the served area table with their digests',
          not sc.validate_manifest(m0) and not m0['unknown'] and not m0['absent']
          and names0 == {n.lower() for _f, n in required_names(mst)}
          and {sc.server_input_name(f['root'], f['path']): f['sha256'] for f in m0['inputs']['server_files']}
          == sc.served_tables(mst, BANNERS), (sc.validate_manifest(m0), m0['unknown'], m0['absent'], len(names0)))
    broker = Broker(PORT)

    def report(srv, served, manifest, label, **want):
        broker.wait_ready()
        cov = cw.coverage(broker, build=BUILD)
        offline = sc.evaluate(fx['policy'], manifest, sc.Content(content), served)
        verdict(check, label, cov, offline, **want)
        return cov, offline

    # 1. Otherwise complete: generated from what the server serves.
    write_system(fx, m0)
    served = sc.served_tables(mst, BANNERS)
    with server(exe, 'baseline') as srv:
        cov, _off = report(srv, served, m0, 'otherwise complete', complete=True)
        tables = status_tables(broker)
        check('otherwise complete: the status lists what the server serves (T rows) -- the six tables with the '
              'digests of the bytes it parsed, the area table with its served projection\'s -- exactly '
              'startup_coverage.server_sources()', tables == served and sorted(tables) == sorted(sc.server_sources()),
              tables)
        rows = served_rows(srv)
        live = served_names(rows)
        check('otherwise complete: Initialize, UserInfo and CampaignMissionGet carry the served tables\' rows, and '
              'they derive exactly the names the generator predicts (the area list with the client\'s dungeons)',
              live == file_names(mst), {k: (len(v), len(file_names(mst).get(k, []))) for k, v in live.items()})
        check('otherwise complete: the projection of the area rows UserInfo actually sent is the server\'s digest '
              'and the generator\'s prediction (served_area_rows ports the curation exactly)',
              projection_of(rows) == tables.get(SERVED_AREA) == served[SERVED_AREA],
              (projection_of(rows)[:16], tables.get(SERVED_AREA, '')[:16], served[SERVED_AREA][:16]))
        baseline_text = cov['text']
        print(f'  served banner names: {live.get("Pk5F1vhx")}; served areas: {len(rows["3SG2wX0R"])}')
    check('otherwise complete: the server log names each table it serves and says the manifest is bound',
          f'content broker: the startup manifest is bound to the {len(served)} response table(s) this server serves'
          in server_log('baseline') and all(f'serves response table {n} (' in server_log('baseline') for n in served),
          server_log('baseline')[-600:])

    # 2. The finding: the banner table changed to name another asset, the OLD manifest kept.
    table = json.loads(original)
    table['Pk5F1vhx'][0]['1gDkL6XR'] = CHANGED
    (mst / BANNER).write_text(json.dumps(table, indent=2), encoding='utf-8')
    served = sc.served_tables(mst, BANNERS)
    m1 = generate(fx, mst)
    with server(exe, 'changed_old_manifest') as srv:
        live = served_names(served_rows(srv))
        check(f'the finding: Initialize now serves {CHANGED} (the requirement changed)',
              CHANGED in live.get('Pk5F1vhx', []), live.get('Pk5F1vhx'))
        check(f'the finding: regenerated from the served table, the manifest requires {CHANGED}, which the old one '
              'does not (the old manifest is stale)', CHANGED in m1['sets']['background']
              and CHANGED not in m0['sets']['background'] and CHANGED in m1['absent'],
              sorted(set(m1['sets']['background']) ^ names0))
        reason = sc.server_binding(m0, served)
        cov, _off = report(srv, served, m0, 'the finding: the old manifest against the changed table',
                           complete=False, reason=reason)
        check('the finding: the reason names the table and both digests',
              BANNER in (cov.get('reason') or '') and m0_digest(m0, BANNER)[:16] in (cov.get('reason') or '')
              and served[BANNER][:16] in (cov.get('reason') or ''), cov.get('reason'))
        print(f'  the finding: complete {cov.get("complete")}; reason {cov.get("reason")}')
    check('the finding: the server log warns that the manifest does not match, with the same reason',
          f'content broker: {reason}; coverage reports stay incomplete' in server_log('changed_old_manifest'),
          server_log('changed_old_manifest')[-600:])

    # 3. Regenerated from the changed table: honest about the missing asset; with it added, complete.
    write_system(fx, m1)
    with server(exe, 'regenerated_absent') as srv:
        cov, _off = report(srv, served, m1, f'regenerated: {CHANGED} required and in no source',
                           complete=False, reason='set background: 1 absent')
        check(f'regenerated: the report names {CHANGED} as absent', ('background', 'absent', CHANGED) in set(cov['P']),
              cov['P'])
    cw.put(content / 'banner' / CHANGED, b'fixture ' + CHANGED.encode())
    m2 = generate(fx, mst)
    write_system(fx, m2)
    with server(exe, 'regenerated') as srv:
        report(srv, served, m2, 'regenerated with the asset present: bound to the changed table', complete=True)

    # 4. Restored: the original table and manifest.
    (content / 'banner' / CHANGED).unlink()
    (mst / BANNER).write_bytes(original)
    write_system(fx, m0)
    served = sc.served_tables(mst, BANNERS)
    plate = first_plate(mst)
    served_ids = {r['VjCY7rX4'] for r in sc.served_area_rows(mst, BANNERS)}
    served_row = next(i for i, a in enumerate(json.loads(area_original)['3SG2wX0R']) if a['VjCY7rX4'] in served_ids)
    translated = plate[:-4] + '_EN.png'
    with server(exe, 'restored') as srv:
        cov, _off = report(srv, served, m0, 'restored: the original table and manifest', complete=True)

        # 5. Snapshot, not disk: what the server serves cannot move while it runs.
        before = (cov['text'], status_tables(broker), served_names(served_rows(srv)))
        (mst / BANNER).write_text(json.dumps(table, indent=2), encoding='utf-8')
        time.sleep(1.0)
        after = (cw.coverage(broker, build=BUILD)['text'], status_tables(broker), served_names(served_rows(srv)))
        check('snapshot: the table rewritten on disk while the server runs -- the served rows, the status T rows and '
              'the report are unchanged (parsed once at boot, never reloaded)', after == before,
              {'report same': after[0] == before[0], 'status same': after[1] == before[1],
               'banner served': after[2].get('Pk5F1vhx')})
        (mst / BANNER).unlink()
        time.sleep(1.0)
        gone = (cw.coverage(broker, build=BUILD)['text'], status_tables(broker), served_names(served_rows(srv)))
        check('snapshot: the table deleted on disk while the server runs -- still unchanged', gone == before,
              {'report same': gone[0] == before[0], 'status same': gone[1] == before[1]})
        cw.put(BANNERS / translated, b'fixture ' + translated.encode())
        areas = json.loads(area_original)
        areas['3SG2wX0R'][served_row]['b5VveUd8'] = AREA_CHANGED
        (mst / 'area_mst.json').write_text(json.dumps(areas, indent=2), encoding='utf-8')
        time.sleep(1.0)
        moved = (cw.coverage(broker, build=BUILD)['text'], status_tables(broker), served_names(served_rows(srv)))
        check(f'snapshot (Session 19): area_mst.json edited and {translated} put in the banner folder while the server '
              'runs -- the served area rows, the status and the report are unchanged (synthesized once at boot)',
              moved == before, {'report same': moved[0] == before[0], 'status same': moved[1] == before[1],
                                'areas': len(moved[2].get('3SG2wX0R', []))})
    (mst / BANNER).write_bytes(original)
    (mst / 'area_mst.json').write_bytes(area_original)
    (BANNERS / translated).unlink()

    # 6. Rows deleted: the banner table emptied, the server restarted with the old manifest.
    (mst / BANNER).write_text(json.dumps({'Pk5F1vhx': []}, indent=2), encoding='utf-8')
    served = sc.served_tables(mst, BANNERS)
    with server(exe, 'rows_deleted') as srv:
        live = served_names(served_rows(srv))
        check('rows deleted: Initialize serves no banner row (the requirement changed: nothing to ask for)',
              live.get('Pk5F1vhx') == [], live.get('Pk5F1vhx'))
        report(srv, served, m0, 'rows deleted: the old manifest against the emptied table', complete=False,
               reason=sc.server_binding(m0, served))
    (mst / BANNER).write_bytes(original)

    # 7. The served area table (Session 19): the banner folder, then an area row.
    cw.put(BANNERS / translated, b'fixture ' + translated.encode())
    served = sc.served_tables(mst, BANNERS)
    with server(exe, 'banner_translated') as srv:
        rows = served_rows(srv)
        live = served_names(rows)
        check(f'served area: {translated} in the server\'s banner folder at boot -> UserInfo serves that plate '
              'instead (an additional required name) and the projection moves with it',
              translated.lower() in live['3SG2wX0R'] and translated.lower() not in names0
              and projection_of(rows) == status_tables(broker).get(SERVED_AREA) == served[SERVED_AREA],
              (translated, len(live['3SG2wX0R'])))
        reason = sc.server_binding(m0, served)
        report(srv, served, m0, 'served area: the old manifest against the translated banner', complete=False,
               reason=reason)
        check('served area: the reason names served:3SG2wX0R (the projection), not a file',
              reason.startswith('the manifest does not match the response tables this server serves: '
                                'served:3SG2wX0R: derived from'), reason)
    cw.put(content / 'dungeon' / translated, b'fixture ' + translated.encode())
    m_en = generate(fx, mst)
    write_system(fx, m_en)
    with server(exe, 'banner_regenerated') as srv:
        report(srv, served, m_en, 'served area: regenerated for that server (the translated plate in the tree): '
               'bound again', complete=True)
    (BANNERS / translated).unlink()
    served = sc.served_tables(mst, BANNERS)
    with server(exe, 'banner_removed') as srv:
        report(srv, served, m_en, 'served area: the banner removed and the server restarted -- it serves the '
               'original plate again, the translated manifest is refused', complete=False,
               reason=sc.server_binding(m_en, served))
    (content / 'dungeon' / translated).unlink()
    areas = json.loads(area_original)
    areas['3SG2wX0R'][served_row]['b5VveUd8'] = AREA_CHANGED
    (mst / 'area_mst.json').write_text(json.dumps(areas, indent=2), encoding='utf-8')
    served = sc.served_tables(mst, BANNERS)
    m_area = generate(fx, mst)
    write_system(fx, m0)
    with server(exe, 'area_row_changed') as srv:
        live = served_names(served_rows(srv))
        check(f'served area: an area row naming {AREA_CHANGED} -> UserInfo serves it; regenerated, the manifest '
              'requires it (absent: in no source)', AREA_CHANGED in live['3SG2wX0R']
              and AREA_CHANGED in m_area['sets']['background'] and AREA_CHANGED in m_area['absent']
              and AREA_CHANGED not in names0, live['3SG2wX0R'][:3])
        report(srv, served, m0, 'served area: the old manifest against the changed area row', complete=False,
               reason=sc.server_binding(m0, served))
    (mst / 'area_mst.json').write_bytes(area_original)
    served = sc.served_tables(mst, BANNERS)
    with server(exe, 'area_restored') as srv:
        report(srv, served, m0, 'served area: area_mst.json restored, the server restarted: rebound', complete=True)

    # 8. Unbound, partial, extra, wrong digest: each refused with the broker's reason.
    files = m0['inputs']['server_files']
    raid = {'root': 'mst', 'path': 'raid_point_mst.json', 'sha256': sc.sha256_file(mst / 'raid_point_mst.json')}
    wrong = [dict(f, sha256='0' * 64) if f['path'] == 'dbb_mst.json' else f for f in files]
    variants = [
        ('unbound: no server files (an old manifest)', {k: v for k, v in m0['inputs'].items() if k != 'server_files'}),
        ('partial: a served table left out', dict(m0['inputs'], server_files=[f for f in files if f['path'] != BANNER])),
        ('partial: the served area table left out (Session 19)',
         dict(m0['inputs'], server_files=[f for f in files if f['root'] != 'served'])),
        ('extra: a table no response serves named too (an unrelated file)', dict(m0['inputs'], server_files=files + [raid])),
        ('wrong digest: dbb_mst.json', dict(m0['inputs'], server_files=wrong)),
    ]
    for n, (label, inputs) in enumerate(variants):
        variant = dict(m0, inputs=inputs)
        write_system(fx, variant)
        with server(exe, f'variant{n}') as srv:
            report(srv, served, variant, label, complete=False, reason=sc.server_binding(variant, served))

    # 9. Malformed or repeated entries, an omitted client binding: the manifest is refused.
    bad = [
        ('malformed: a table named twice', dict(m0['inputs'], server_files=files + [dict(files[0], path=files[0]['path'].upper())])),
        ('malformed: a table under another root', dict(m0['inputs'], server_files=[dict(files[0], root='package')] + files[1:])),
        ('malformed: a table in a folder', dict(m0['inputs'], server_files=[dict(files[0], path='sub/' + files[0]['path'])] + files[1:])),
        ('omitted client binding: inputs.tables records the dungeon table, client_files does not bind it (Session 19)',
         dict(m0['inputs'], client_files=[f for f in m0['inputs']['client_files'] if 'B57MJYoF' not in f['path']],
              tables={'M_AREA_MST': {'served': '3SG2wX0R', 'joined': [
                  {'version': 1003, 'parts': [f['path'] for f in m0['inputs']['client_files'] if 'B57MJYoF' in f['path']]}]}})),
    ]
    for n, (label, inputs) in enumerate(bad):
        variant = dict(m0, inputs=inputs)
        write_system(fx, variant)
        with server(exe, f'malformed{n}') as srv:
            broker.wait_ready()
            cov = cw.coverage(broker, build=BUILD)
        check(f'{label}: refused (manifest_error), complete 0, never proved; the offline schema refuses it too',
              cov.get('complete') == '0' and not cov['proved'] and cov.get('manifest') == 'none'
              and 'inputs.' in cov.get('manifest_error', '') and bool(sc.validate_manifest(variant)),
              {k: cov.get(k) for k in ('complete', 'manifest', 'manifest_error', 'reason')})

    write_system(fx, m0)
    check('deploy/mst was only read: its six response tables are unchanged',
          sc.served_tables(REAL_MST, None) == real_before, sc.served_tables(REAL_MST, None))
    check('the baseline report was a real report', baseline_text.startswith('bfcp 2\ncoverage 1\n'), baseline_text[:80])
    return check.summary('test_content_server_tables')


def m0_digest(manifest: dict, path: str) -> str:
    return next(f['sha256'] for f in manifest['inputs']['server_files'] if f['path'] == path)


