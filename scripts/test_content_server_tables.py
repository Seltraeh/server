"""Startup coverage bound to the server's own response tables (Session 18 correction, QC 2026-10-22;
Session 19: the area table the server synthesizes).

    python scripts/test_content_server_tables.py SERVER_EXE

scripts/startup_coverage.py derives the exact names of six startup lists from tables the SERVER sends
(inputs.server_files: dungeon_key, banner_info, general_event, dbb, grand_mission and grand_mission_map
under its mst_root) and, since Session 19, the area list from the area table UserInfo sends at 3SG2wX0R,
which the server SYNTHESIZES at boot from area_mst.json, dungeon_mst.json and the translated banners it
finds in its working folder (ServerCache::clientAreaMst; bound by the digest of its served projection,
"served:3SG2wX0R").  Before the correction the broker bound only inputs.client_files, so a manifest
derived from one banner table kept reporting complete 1 after the server started serving another
(docs/CLAUDE_SESSION_18_CORRECTION.md).  This suite runs an isolated server over its own COPY of
deploy/mst (deploy/mst is only read, and checked unchanged at the end), a content tree holding every name
the tables require, and a policy owning all of it:

  otherwise complete  the manifest generated by startup_coverage's own reader and rules from the
                      fixture's tables: complete 1, proved by the DLL's rule; the server's status lists
                      what it serves (T rows) -- exactly startup_coverage.server_sources() -- with the
                      digests of the bytes it parsed and of the area table's served projection; the
                      replies carry rows that derive the same names, and the projection of the area rows
                      UserInfo actually sends is the server's digest and the generator's prediction
  the finding         one banner row's resource field changed to name an asset nobody has, the server
                      restarted with the OLD manifest: Initialize serves the new name, the regenerated
                      manifest requires it -> the broker must say complete 0, naming the table and both
                      digests (the candidate before the correction said complete 1 here)
  regenerated         the manifest regenerated from the changed table: honest about the missing asset
                      (absent, complete 0); with the asset added and regenerated again: complete 1
  restored            the original table and manifest: complete 1 again
  snapshot, not disk  the table rewritten, then deleted, on disk while the server runs -- and, Session 19,
                      area_mst.json edited and a translated banner put in its banner folder: the served
                      rows, status and report do not move (the cache parses and synthesizes once at boot).
                      The suite never restarts WITHOUT a table: the cache's LoadJson throws, the process
                      logs a fatal exception, never listens, and stays behind as an unkillable zombie
                      holding the executable and the fixture save until a reboot (seen once, 2026-10-22,
                      the Session 18 server 995a088d)
  rows deleted        the table's rows deleted (an empty list) and the server restarted with the old
                      manifest: Initialize serves no banner row, complete 0 with the table's reason
  served area table   (Session 19) a translated banner appears in the server's banner folder, then an area
                      row names another image: each time UserInfo serves an additional name, the old
                      manifest is refused naming served:3SG2wX0R, and a manifest regenerated for that
                      server is bound again; the banner removed, the server serves the original again
  unbound / partial   no server files (an old manifest), a served table left out (a file, Session 19 the
                      served area table), a table no response serves named too, a wrong digest: complete
                      0, each with the broker's reason, which is startup_coverage.server_binding word for word
  malformed           a repeated entry, another root, a path in a folder, an omitted client binding:
                      manifest_error, complete 0 (every schema case also runs against the server in
                      test_content_coverage_wire.py)

Every verdict is checked three ways: the report's `complete`, the DLL's rule
(content_provider_client_test.parse_coverage) and startup_coverage.evaluate with what the server serves.
Logs and the fixture: out/qa/current/session19/server_tables.
"""
